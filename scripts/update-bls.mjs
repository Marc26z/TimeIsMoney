import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const dataFile = path.join(root, "src", "data.js");
const seriesId = "LEU0252881500";
const endpoint = "https://api.bls.gov/publicAPI/v2/timeseries/data/";

const current = (await import(`${new URL(`file://${dataFile}`).href}?t=${Date.now()}`)).BLS;
const thisYear = new Date().getUTCFullYear();

const response = await fetch(endpoint, {
  method: "POST",
  headers: { "Content-Type": "application/json" },
  body: JSON.stringify({
    seriesid: [seriesId],
    startyear: String(thisYear - 1),
    endyear: String(thisYear),
  }),
});

if (!response.ok) {
  throw new Error(`BLS API returned HTTP ${response.status}`);
}

const payload = await response.json();
if (payload.status !== "REQUEST_SUCCEEDED") {
  throw new Error(`BLS API error: ${payload.message?.join("; ") || payload.status}`);
}

const series = payload.Results?.series?.find((item) => item.seriesID === seriesId);
if (!series) throw new Error(`BLS series ${seriesId} was not returned`);

const numeric = series.data
  .filter((row) => /^\d+(?:\.\d+)?$/.test(row.value))
  .sort((a, b) => Number(a.year) - Number(b.year) || a.period.localeCompare(b.period));

const latest = numeric.at(-1);
if (!latest) throw new Error("BLS returned no numeric observations");

const quarter = latest.period.replace("Q0", "Q");
const periodLabel = `Q${quarter.slice(1)} ${latest.year}`;
const period = latest.year + " " + quarter;
const weeklyEarnings = Number(latest.value);
const releaseDate = period === current.period ? current.releaseDate : "";
const retrieved = new Date().toISOString().slice(0, 10);

const next = {
  ...current,
  period,
  periodLabel,
  weeklyEarnings,
  releaseDate,
  retrieved,
};

const contents = `// Generated by scripts/update-bls.mjs. Source: U.S. Bureau of Labor Statistics.
export const BLS = Object.freeze(${JSON.stringify(next, null, 2)});
`;

await writeFile(dataFile, contents);
console.log(
  `Updated ${path.relative(root, dataFile)}: ${periodLabel}, $${weeklyEarnings}/week (retrieved ${retrieved})`,
);
